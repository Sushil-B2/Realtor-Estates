#!/usr/bin/env python3
"""
Documentation facts — measured, not typed.

    python3 scripts/doc_facts.py            # rewrite the facts block in README.md
    python3 scripts/doc_facts.py --check    # exit 1 if any doc is stale (CI gate)
    python3 scripts/doc_facts.py --json     # the numbers alone

The drift this exists to prevent: by v1.10.0 the README advertised 71 routes and
87 tests, `docs/04` advertised 71 routes, `docs/09` advertised 69 routes and 28
tests, and `PLANS.md` advertised 28 tests and 15 documents. The real numbers were
118, 275 and 23. Every one of those was true when it was written, which is
exactly why a number typed into prose rots.

So the counts live in one generated block (`<!-- facts:begin -->`) and every doc
that quotes a number is listed in `STALE_PATTERNS` and checked against it.
"""
from __future__ import annotations

import argparse
import ast
import glob
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BEGIN = "<!-- facts:begin -->"
END = "<!-- facts:end -->"


def count_routes() -> int:
    src = open(os.path.join(ROOT, "app", "api.py"), encoding="utf-8").read()
    return len(re.findall(r"^@route\(", src, re.M))


def count_collections() -> int:
    src = open(os.path.join(ROOT, "app", "store.py"), encoding="utf-8").read()
    block = re.search(r"COLLECTIONS\s*=\s*\[(.*?)\]", src, re.S)
    if not block:
        return 0
    return len([line for line in block.group(1).splitlines() if line.strip().startswith('"')])


def count_tests() -> tuple[int, int]:
    """Test functions and files, by AST — no server, no collection run."""
    total = files = 0
    for path in sorted(glob.glob(os.path.join(ROOT, "tests", "test_*.py"))):
        files += 1
        tree = ast.parse(open(path, encoding="utf-8").read())
        total += sum(1 for node in ast.walk(tree)
                     if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
                     and node.name.startswith("test_"))
    return total, files


OFFLINE = False


def count_test_cases() -> int:
    """What `pytest` actually collects (parametrize expands one function into many).

    Skipped when we are *inside* a pytest run (`--offline`): shelling out to pytest
    from a test would recurse.
    """
    if OFFLINE:
        return 0
    try:
        out = subprocess.run([sys.executable, "-m", "pytest", "--collect-only", "-q", "tests"],
                             cwd=ROOT, capture_output=True, text=True, timeout=120).stdout
        for line in reversed(out.strip().splitlines()):
            match = re.search(r"(\d+) tests? collected", line)
            if match:
                return int(match.group(1))
    except Exception:
        pass
    return 0


def count_docs() -> int:
    return len(glob.glob(os.path.join(ROOT, "docs", "*.md")))


def count_glob(pattern: str) -> int:
    return len(glob.glob(os.path.join(ROOT, pattern)))


def facts() -> dict:
    tests, test_files = count_tests()
    return {
        "api_routes": count_routes(),
        "test_cases": count_test_cases(),
        "collections": count_collections(),
        "test_functions": tests,
        "test_files": test_files,
        "proof_scripts": count_glob("scripts/proof_*.py") + count_glob("scripts/proof-*.mjs"),
        "neon_functions": count_glob("functions/*.ts"),
        "migrations": count_glob("db/*.sql"),
        "docs": count_docs(),
        "js_modules": count_glob("web/js/*.js"),
        "app_modules": count_glob("app/*.py"),
    }


def block(f: dict) -> str:
    rows = [
        ("API routes", f"`app/api.py`", f["api_routes"]),
        ("Collections", "`app/store.py`", f["collections"]),
        ("Test functions", f"`tests/` ({f['test_files']} files)", f["test_functions"]),
        ("Test cases collected", "`pytest --collect-only`", f["test_cases"]),
        ("Proof scripts", "`scripts/proof*` (py + mjs)", f["proof_scripts"]),
        ("Neon Functions", "`functions/*.ts`", f["neon_functions"]),
        ("SQL migrations", "`db/*.sql`", f["migrations"]),
        ("Documents", "`docs/*.md`", f["docs"]),
        ("App modules", "`app/*.py`", f["app_modules"]),
        ("JS modules", "`web/js/*.js`", f["js_modules"]),
    ]
    width = max(len(name) for name, _, _ in rows)
    lines = [BEGIN, "",
             "| What | Where | Count |",
             "|---|---|---|"]
    lines += [f"| {name} | {where} | **{count}** |" for name, where, count in rows]
    lines += ["", "<!-- generated by scripts/doc_facts.py — do not edit by hand -->", END]
    return "\n".join(lines)


# (file, regex, what the sentence is probably trying to say, current fact key)
STALE_PATTERNS: list[tuple[str, str, str, str]] = [
    ("README.md", r"\b(\d{2,3}) API routes\b", "API routes", "api_routes"),
    ("README.md", r"\b(\d{2,3}) routes\b", "API routes", "api_routes"),
    ("README.md", r"\b(\d{2,3}) automated tests\b", "test functions", "test_functions"),
    ("README.md", r"\b(\d{2,3}) tests\b", "test functions", "test_functions"),
    ("README.md", r"\b(\d{2,3}) collected (?:tests|cases)", "collected cases", "test_cases"),
    ("docs/04-API-AND-WEBHOOKS.md", r"`?(\d{2,3}) routes`?", "API routes", "api_routes"),
    ("docs/09-ROADMAP-AND-ECONOMICS.md", r"(\d{2,3}) API\s*\n?\s*routes", "API routes", "api_routes"),
    ("docs/09-ROADMAP-AND-ECONOMICS.md", r"(\d{2,3}) pytest", "test functions", "test_functions"),
    ("docs/03-DATA-MODEL.md", r"^(\d{1,3}) collections", "collections", "collections"),
    ("PLANS.md", r"(\d+) test functions", "test functions", "test_functions"),
    ("PLANS.md", r"(\d+) collected", "collected cases", "test_cases"),
    ("PLANS.md", r"(\d+) proof scripts", "proof scripts", "proof_scripts"),
    ("docs/09-ROADMAP-AND-ECONOMICS.md", r"(\d{2,3}) collected tests", "collected cases", "test_cases"),
    ("docs/09-ROADMAP-AND-ECONOMICS.md", r"(\d+) proof scripts", "proof scripts", "proof_scripts"),
    ("PLANS.md", r"✅ (\d+) documents", "documents", "docs"),
    ("docs/01-PRD.md", r"(\d{2,3}) API routes", "API routes", "api_routes"),
]


def check() -> int:
    f = facts()
    problems: list[str] = []

    readme = open(os.path.join(ROOT, "README.md"), encoding="utf-8").read()
    if BEGIN not in readme or END not in readme:
        problems.append("README.md has no facts block (run scripts/doc_facts.py)")
    else:
        current = readme.split(BEGIN, 1)[1].split(END, 1)[0]
        expected = block(f).split(BEGIN, 1)[1].split(END, 1)[0]

        def normalise(text: str) -> str:
            # offline mode cannot collect test cases; do not fail on that one row
            if not OFFLINE:
                return text.strip()
            return "\n".join(line for line in text.strip().splitlines()
                             if "Test cases collected" not in line)

        if normalise(current) != normalise(expected):
            problems.append("README.md facts block is stale (run scripts/doc_facts.py)")

    for rel, pattern, label, key in STALE_PATTERNS:
        path = os.path.join(ROOT, rel)
        if not os.path.exists(path):
            continue
        text = open(path, encoding="utf-8").read()
        body = text.split(BEGIN, 1)[0] + (text.split(END, 1)[1] if END in text else "")
        for match in re.finditer(pattern, body, re.M):
            quoted = [g for g in match.groups() if g and g.isdigit()]
            if not quoted:
                continue
            values = {int(g) for g in quoted}
            allowed = {int(f[key])}
            if key == "test_functions":
                allowed.add(int(f.get("test_cases") or 0))
            if key == "test_cases":
                # offline mode cannot collect; the README block is the record of the real run
                if OFFLINE:
                    continue
                allowed.add(int(f.get("test_functions") or 0))
            if not (values & allowed):
                line_no = body[: match.start()].count("\n") + 1
                problems.append(f"{rel}:{line_no} quotes {match.group(0).strip()!r} for {label}; "
                                f"measured {f[key]}")

    if problems:
        print(f"doc_facts: {len(problems)} stale claim(s)")
        for p in problems:
            print("  ✗ " + p)
        print("\nFix with: python3 scripts/doc_facts.py")
        return 1
    print(f"doc_facts: OK — {f['api_routes']} routes, {f['test_functions']} tests, "
          f"{f['collections']} collections, {f['docs']} docs")
    return 0


def write() -> int:
    f = facts()
    path = os.path.join(ROOT, "README.md")
    text = open(path, encoding="utf-8").read()
    if BEGIN in text and END in text:
        head, rest = text.split(BEGIN, 1)
        tail = rest.split(END, 1)[1]
        text = head + block(f) + tail
    else:
        text = text.rstrip() + "\n\n" + block(f) + "\n"
    open(path, "w", encoding="utf-8").write(text)
    print(f"doc_facts: wrote README facts block — {f['api_routes']} routes, "
          f"{f['test_functions']} tests, {f['collections']} collections, {f['docs']} docs")
    return 0


def main() -> int:
    global OFFLINE
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--offline", action="store_true",
                    help="skip the pytest collection subprocess (used from inside pytest)")
    args = ap.parse_args()
    OFFLINE = args.offline
    if args.json:
        print(json.dumps(facts(), indent=2))
        return 0
    return check() if args.check else write()


if __name__ == "__main__":
    sys.exit(main())
